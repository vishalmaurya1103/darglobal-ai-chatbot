-- Lakebase Search on Neon: pgvector-compatible ANN indexes and BM25 ranking.
CREATE EXTENSION IF NOT EXISTS lakebase_vector CASCADE;
CREATE EXTENSION IF NOT EXISTS lakebase_text;

-- One row per project, listing or article. Structured fields drive filters and analytics.
CREATE TABLE IF NOT EXISTS properties (
  id            text PRIMARY KEY,
  source        text NOT NULL CHECK (source IN ('darglobal', 'wasalt')),
  kind          text NOT NULL CHECK (kind IN ('project', 'listing', 'article')),
  url           text NOT NULL,
  title         text NOT NULL,
  country       text,
  city          text,
  district      text,
  property_type text,
  purpose       text CHECK (purpose IN ('sale', 'rent')),
  price         numeric,
  currency      text,
  price_period  text,
  bedrooms_min  smallint,
  bedrooms_max  smallint,
  area_sqm      numeric,
  status        text,
  scraped_at    timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS properties_price_idx ON properties (price) WHERE price IS NOT NULL;

-- Retrieval units. `content` already carries its property context (title, location, section).
CREATE TABLE IF NOT EXISTS chunks (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id text NOT NULL REFERENCES properties (id) ON DELETE CASCADE,
  heading     text NOT NULL,
  content     text NOT NULL,
  embedding   vector(1024) NOT NULL, -- baai/bge-m3
  content_tsv tsvector GENERATED ALWAYS AS (to_tsvector('english', content)) STORED
);

CREATE INDEX IF NOT EXISTS chunks_property_idx ON chunks (property_id);
CREATE INDEX IF NOT EXISTS chunks_embedding_ann ON chunks USING lakebase_ann (embedding vector_cosine_ops);
CREATE INDEX IF NOT EXISTS chunks_content_bm25 ON chunks USING lakebase_bm25 (content_tsv) WITH (k1 = 1.2, b = 0.75);
